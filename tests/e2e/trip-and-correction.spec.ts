test('failed correction retains chosen location and succeeds on retry', async ({ page }) => {
  await boot(page)
  await openTrip(page, 'Rome with family')
  await page.getByRole('button', { name: 'Set location', exact: true }).click()
  await page.getByRole('button', { name: 'Same place as previous photo' }).click()
  const chosen = await page.locator('.lpick-chosen').innerText()
  await failNext(page, 'patchLocation')
  await page.getByRole('button', { name: 'Save location' }).click()
  await expect(page.getByRole('alert')).toContainText('location could not be saved')
  await expect(page.locator('.lpick-chosen')).toHaveText(chosen)
  await page.getByRole('button', { name: 'Save location' }).click()
  await expect(page.locator('.trip-saved')).toContainText('Location saved')
  await expect(page.getByRole('button', { name: 'Set location', exact: true })).toHaveCount(0)
})

test('Change location can be cancelled without modifying the photo', async ({ page }) => {
  await boot(page)
  await openTrip(page, 'Rome with family')
  const tile = page.locator('.trip-tile').filter({ hasText: 'Colosseum' })
  const before = await tile.innerText()
  await tile.getByRole('button', { name: 'Change location' }).click()
  await expect(page.locator('.lpick-chosen')).toContainText('Current location')
  await page.getByRole('combobox', { name: 'Search for the place' }).press('Escape')
  // First Escape closes the focused search's suggestions; next closes correction.
  if (await page.locator('.trip-correct').count()) await page.keyboard.press('Escape')
  await expect(page.locator('.trip-correct')).toHaveCount(0)
  await expect(tile).toHaveText(before, { useInnerText: true })
})

test('map click and pin drag set coordinates and can be saved', async ({ page }) => {
  await boot(page)
  await openTrip(page, 'Rome with family')
  await page.getByRole('button', { name: 'Set location', exact: true }).click()
  const map = page.locator('.lpick-map')
  await map.click({ position: { x: 120, y: 120 } })
  await expect(page.locator('.lpick-chosen')).toContainText('Pin dropped on the map')
  const pin = page.locator('.lpick-pin')
  await pin.scrollIntoViewIfNeeded()
  const box = await pin.boundingBox()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(box!.x + box!.width / 2 + 25, box!.y + box!.height / 2 + 20, { steps: 10 })
  await page.mouse.up()
  await expect(page.locator('.lpick-chosen')).toContainText('Pin moved on the map')
  await checkLayout(page)
  await page.getByRole('button', { name: 'Save location' }).click()
  await expect(page.locator('.trip-saved')).toContainText('Location saved')
})

