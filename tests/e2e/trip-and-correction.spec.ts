test('Trip gallery, journey, upload toggle, map and back controls work', async ({ page }) => {
  await boot(page)
  await openTrip(page, 'Rome with family')
  await expect(page.locator('.trip-tile')).toHaveCount(3)
  await expect(page.getByRole('button', { name: 'Gallery', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Journey', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Journey', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('heading', { name: 'No capture date', exact: true })).toBeVisible()
  await expect(page.locator('.trip-day')).toHaveCount(3)
  await page.getByRole('button', { name: 'Gallery', exact: true }).click()
  await expect(page.locator('.trip-tile')).toHaveCount(3)
  const upload = page.getByRole('button', { name: 'Upload photos', exact: true })
  await upload.click()
  await expect(upload).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.upl')).toBeVisible()
  await upload.click()
  await expect(page.locator('.upl')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show on map', exact: true }).click()
  await expect(page.getByLabel('Trip', { exact: true })).toHaveValue('trip-rome')
  await dashboard(page)
  await openTrip(page, 'Rome with family')
  await page.locator('.trip-back').click()
  await expect(page.locator('.trip-card')).toHaveCount(3)
})

